// Order — минимальная модель заказа для конвейера.
// В капстоуне используйте domain.Order.
type Order struct {
	ID     string
	Status string
	Total  int64 // в копейках
}

// Stage — этап конвейера: читает заказы из in, пишет результат в out.
//
// Контракт этапа:
//   - обрабатывает каждый заказ ровно один раз (1:1) и сохраняет порядок
//     своего потока — иначе Run не может гарантировать порядок на выходе;
//   - НЕ закрывает out — каналы закрывает только Run (их владелец);
//   - при отмене контекста возвращает ошибку (обычно ctx.Err());
//   - когда in закрыт и опустошён — просто возвращается.
type Stage func(ctx context.Context, in <-chan Order, out chan<- Order) error

